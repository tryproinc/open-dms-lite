package com.trypro.opendms.ui

/**
 * ドライバーへの周知内容(ASV基本設計書5章)。
 *
 * ## 根拠(一次情報・必須要件)
 * 国交省ASV「ドライバーモニタリング(眠気・居眠り検知)システム 基本設計書」5章および
 * 「(脇見等検知)システム 基本設計書」5章は、以下の5項目を
 * 「取扱説明書、表示等によりドライバーに対し、適切に周知すること」と定めている。
 *
 * 1. 本システムの目的および効果
 * 2. 本システムの作動開始の条件と作動しない場合について
 * 3. 本システムに基づいて発する音、表示等 及び その意味
 * 4. 本システムの機能限界
 * 5. その他の使用上の注意
 *
 * 文言は眠気編5章の【解説】が挙げる具体例をほぼそのまま使っている。ただし**2項だけは
 * Open DMS固有の差がある**: 解説の例示は「停車中は作動しない」だが、本システムは
 * 運行開始/終了を手動で操作する設計のため「運行開始から終了まで作動する」が正しい
 * (脇見・スマホの判定のみ、速度が低いと一時的に止まる)。
 *
 * ASVは提示方法を規定していない(「取扱説明書、表示等により」)。本アプリはPREFLIGHTから
 * 開ける注意事項画面で全文を読めるようにしている。
 */
object DriverNotice {

    data class Section(val title: String, val body: String)

    /**
     * 周知の本文(ASV眠気5章/脇見5章の5項目)。
     *
     * @param recordLocation 発報時に位置を記録する設定([DayMvpSettings.recordLocationOnEvent])。
     *   **記録するかどうかで文面を変える。**運転者に事実と違うことを表示しないため。
     */
    fun sections(recordLocation: Boolean = false): List<Section> = listOf(
        Section(
            title = "1. このシステムの目的と効果",
            body = "運転者の眠気が強い状態や居眠り状態、前方以外を見続けている状態を、" +
                "スマートフォンの前面カメラで検知し、音・振動・画面で知らせることで安全運転を支援します。" +
                "\n\n" +
                "検知しているのは次の4つです。" +
                "\n・長く目を閉じている" +
                "\n・頭が前後に倒れる動き(こっくり)" +
                "\n・あくびが繰り返し出ている" +
                "\n・前方以外を長く見ている" +
                "\n\n" +
                "このシステムは、眠気そのもの(生理的な眠さ)を測ったり予測したりするものではありません。" +
                "眠気と同時に起こりやすい体の動き(頭がこっくりと揺れる、目が細くなる・閉じる、あくびが出る)や、" +
                "よそ見などの行動をカメラで検知して知らせます。" +
                "検知の考え方は、国連の車両規則 UN R182(運転者の眠気・注意の警報)と UN R183(脇見の警報)を参照しています" +
                "(規則への適合を示すものではありません)。",
        ),
        Section(
            title = "2. 作動する条件と、作動しない場合",
            body = "「運行開始」を押してから「運行終了」を押すまでの間、作動します。" +
                "アプリを前面に表示したままにしてください。他のアプリを開いたり画面を消したりすると停止します。" +
                "\n\n" +
                "運行開始の後、一度時速20kmを超えるまで警告は出ません(出発前の準備で鳴らさないため)。" +
                "位置情報を許可していない場合は、運行開始からすぐ警告を出します。" +
                "\n\n" +
                "運行開始の前に、10秒間の較正(正面を見て姿勢を覚えさせる操作)が必要です。" +
                "スマートフォンを置き直したときは、必ず較正をやり直してください。" +
                "\n\n" +
                "前方以外を見ていることの検知と、ながら運転の検知は、" +
                "速度が低いとき(信号待ち・休憩・積卸しなど)は作動しません。" +
                "眠気の検知は停車中でも作動します。" +
                "\n\n" +
                (
                    if (recordLocation) {
                        "位置情報は速度の判定に使用し、**警告が出た地点の位置も記録します**。" +
                            "記録するのは警告が出た瞬間の1点だけで、走行の軌跡は記録しません。"
                    } else {
                        "位置情報は速度の判定にのみ使用し、走行位置は記録しません。"
                    }
                    ) +
                "位置情報を許可しない場合でも監視は続きますが、停車中にも前方確認の警告が出ることがあります。",
        ),
        Section(
            title = "3. 音・表示の意味と、とるべき行動",
            body = "「休憩を検討してください」(短い音1回)\n" +
                "　目を閉じている時間が長くなっています。休憩できる場所を考えてください。" +
                "\n\n" +
                "「安全な場所で休憩してください」(強い音2回)\n" +
                "　強い眠気の兆候です。安全な場所に停めて休憩してください。" +
                "\n\n" +
                "「眠気の兆候があります 休憩してください」(短い音3回)\n" +
                "　頭が前後に倒れる動きが繰り返し出ています。休憩してください。" +
                "\n\n" +
                "「あくびが続いています 休憩を検討してください」(弱い音1回)\n" +
                "　眠気の初期の兆候です。早めの休憩を考えてください。" +
                "\n\n" +
                "「前を確認してください」(2音)\n" +
                "　前方以外を長く見ています。前方に視線を戻してください。" +
                "大きく横を向いたり手元を見下ろしたりして顔が映らなくなった場合も、" +
                "直前の向きから前方以外を見ているものとして扱います。" +
                "停車中は鳴りませんが、見続けたまま走り出すと鳴ります。" +
                "\n\n" +
                "「顔を確認できません」(低い音1回)\n" +
                "　顔が映っていないため監視できていません。取付位置や姿勢を確認してください。" +
                "映らない状態が続く間は、10秒ごとに繰り返し知らせます。" +
                "\n\n" +
                "「監視機能が使用できません」(低い音1回・赤い画面)\n" +
                "　カメラや解析が動作していません。安全な場所でアプリを再起動してください。" +
                "\n\n" +
                "「端末が高温です」(低い音1回)\n" +
                "　直射日光を避けるなど、端末を冷やしてください。高温が続くと監視の精度が落ちます。",
        ),
        Section(
            title = "4. 機能の限界",
            body = "次のような場合には、正しく作動しないことがあります。" +
                "\n・明るさが足りない、逆光になっている" +
                "\n・マスク、帽子、サングラスなど顔や頭に装着物がある" +
                "(マスク着用時はあくびを検知できず、横を向いたときに顔を見失いやすくなります)" +
                "\n・顔の前に遮蔽物がある" +
                "\n・カメラのレンズが汚れている" +
                "\n・運転姿勢が大きく変わっている、顔がカメラの画角から外れている" +
                "\n\n" +
                "また本システムは日中の使用を前提としています。夜間・トンネル内など暗い環境では" +
                "検知できません。" +
                "\n\n" +
                "警告の閾値は、事故を防げることを保証する値ではありません。",
        ),
        Section(
            title = "5. 使用上の注意",
            body = "このシステムを過信しないでください。警告が出ないことは、安全であることを意味しません。" +
                "\n\n" +
                "本システムは、眠気や居眠りの状態にある運転者の運転を補助するものではありません。" +
                "眠気を感じたら、警告の有無にかかわらず休憩してください。" +
                "\n\n" +
                "本システムは医療機器ではなく、健康状態の診断を行うものではありません。" +
                "\n\n" +
                "カメラ映像・顔の画像・顔の特徴点は、端末にも外部にも保存されません。" +
