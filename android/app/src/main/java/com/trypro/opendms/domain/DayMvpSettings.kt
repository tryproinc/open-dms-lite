    /** 同上上限。3.4: 「顔幅がframe幅の20〜60%目安」。D0-006時点では上限側の判定は未実装(既知の制約)。 */
    val maxFaceSizeRatio: Float = 0.60f,
    /** 較正基準に対する相対yawの許容上限(度)。これを超えると判定に使わない。 */
    /**
     * 2026-08-29: 軸修正後の実測で、自然な左右の首振りは相対yawで-48.6°〜+30.3°に達しており、
     * 旧45°では大きく振った側が品質無効になっていた。pitch側(70°)と同様に余裕を持たせる。
     */
    val maxAbsRelativeYawDeg: Float = 60f,
    /** 同上pitch。 */
    /**
     * 2026-08-29実機検証で35°から55°へ変更。自然な「下を向く/上を向く」動作の実測値は
