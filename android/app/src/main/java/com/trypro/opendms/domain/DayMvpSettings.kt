     * 上限を0.85へ広げ、さらに[EyeClosedCalibrationCollector]で「閉眼値+余裕」を下回らないようにした。
     */
    val eyeClosedCalibrationThresholdMin: Float = 0.35f,
    val eyeClosedCalibrationThresholdMax: Float = 0.85f,
    /** 閾値は少なくとも閉眼値からこれだけ上に置く。クランプで閉眼値を下回るのを防ぐ。 */
    val eyeClosedCalibrationMinMarginAboveClosed: Float = 0.05f,
    /**
     * 開との差がこれ未満なら「取れたが不安定」として警告する(較正は通す)。
     * 2026-09-14: サングラス越しでは閉眼が0.55〜0.79の間で試みごとにばらつき、
     * 開いていて下を見たとき(0.75〜0.85)と重なる。差0.40未満はこの領域。
