    /**
     * 「目を閉じてください」の基本時間(ms)。**3秒。**
     *
     * 欲しいのは閉じているときの安定した値1つなので、安定区間が1.5秒あれば足りる。
     * 言われてから閉じ切るまでに0.5〜1秒かかるぶんを見込んで3秒にした。
     * 安定区間が取れなければ[eyeClosedCalibrationMaxDurationMs]まで自動で延長する。
     */
    val eyeClosedCalibrationMinDurationMs: Long = 3_000L,
    /** 延長の上限(ms)。ここまでに安定区間が取れなければ失敗にする。 */
    val eyeClosedCalibrationMaxDurationMs: Long = 6_000L,
    /** 「安定区間」として見る直近の長さ(ms)。この区間の中央値を閉眼の基準にする。 */
    val eyeClosedCalibrationStableWindowMs: Long = 1_500L,
    /** 安定区間に必要な有効フレーム数。20fpsで1.5秒なら30枚入るので、その半分。 */
    val eyeClosedCalibrationMinStableFrames: Int = 15,
    /**
     * 安定区間のばらつき(正規化開眼比の四分位範囲)の上限。
     * これを超える間は「まだ閉じ切っていない/瞬きしている」とみなして待つ。
