    /**
     * あくび1回の成立に必要な連続時間(ms)。
     *
     * 2026-09-23: 1,200→**1,000**。[yawnJawOpenThreshold]を0.35→0.45へ上げたぶん、
     * 閾値を超えている時間が短くなるため同じだけ緩める(そちらのKDocの表を参照)。
