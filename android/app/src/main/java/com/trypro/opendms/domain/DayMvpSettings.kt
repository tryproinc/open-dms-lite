     * | 0.45 | 1.2秒 | なし | 49本 | **3/5** |
     * | 0.50 | 1.2秒 | なし | 45本 | **3/5** |
     * | 0.45 | 1.0秒 | 0.60 | 47本 | 5/5 |
     *
     * そのため連続時間を[yawnMinDurationMs]で1.0秒へ緩め、代わりに深さの条件
     * [yawnMinPeakJawOpen]を足して分離を担わせた。
     */
