     * 実装する。これにより`version`(=較正値の意味)を上げずに済み、全端末の再較正が発生しない。
     * D1-010の実測で個人差が大きいと分かった時点で較正基準の導入を検討する。
     *
     * 2026-08-31: 0.55→**0.45**。「かなり大きく開口しないと判定しないのでは」との指摘を受け、
     * 端末上の全診断ログで`jawOpen`の分布を測った(顔検出時 n=3072)。
     * 中央値0.12・p75 0.28・p90 0.67・最大0.90と**閉口時と開口時がはっきり2分**されており、
     * 0.28〜0.67の間が空いている。会話程度の開口はp75(0.28)側に収まり、実際のあくびは0.67以上へ出る。
     * 空隙の中央寄りに置くことで、小さめのあくびに余裕を持たせつつ会話とは分離を保つ。
     *
     * 2026-08-31(再調整): 0.45→**0.35**。「もう少し小さい開口でも反応してほしい」との要望を受け、
     * 全診断ログ(30本超)で開口区間を数え直した。**1.2秒以上続いた区間(=あくび成立)は
     * 0.45で12本、0.35で15本**と最多になり、0.30・0.25まで下げるとかえって14本へ減る。
     * 短い区間(誤検知候補)は20本→22本とほぼ増えない。
     *
     * この値を下げてもこっくり検出を潰さないのは、あくび中にこっくりを抑制する閾値を
     * [noddingYawnSuppressionJawOpen]として**別に分けた**ため(当初は本閾値を流用しており、
     * 口が少し開くたびにこっくりが止まっていた)。
     *
     * 2026-09-23(再々調整): 0.35→**0.45**。実車で「1度目のあくびで鳴った」と報告を受け、
     * 端末の全診断ログ9本(約9時間)をオフライン再現した。0.35では**ピーク0.47〜0.53の浅い開口**が
