     * 高速域での脇見警告までの継続時間(ms)。**既定3.5秒。**
     *
     * EU委任規則 ADDW ((EU) 2023/2590) は
     * **50km/h超で3.5秒 / 20km/h以上で6秒**を求めている。
     * ASV基本設計書の脇見編は閾値を規定していない(メーカー設定)ので、
     * 数値のある方に合わせる。
     *
     * 速度が取れないとき(GPS未測位)は**厳しい方ではなく[distractionWarningMs]**を使う。
     * 速度が分からないのに短い方で鳴らすと、停車中に誤って鳴らしうるため。
     */
    val distractionWarningMsHighSpeed: Long = 3_500L,
    /** [distractionWarningMsHighSpeed]へ切り替わる速度(km/h)。EU規則の50km/h。 */
    val distractionHighSpeedKph: Float = 50f,
    /**
     * **顔を見失う直前の相対yawがこれ以上なら、見失っている間も脇見として数え続ける。既定15°。**
     *
     * 大きく横を向くと顔の検出が外れる。2026-09-27の机上試験では、マスク着用で約25〜30°、
