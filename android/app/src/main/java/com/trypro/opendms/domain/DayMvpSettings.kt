     * 実車の取付ではインカメラの顔が0.20〜0.26と小さく、下限0.20を割ると判定無効(点が赤)になる
     * (2026-10-15、近づくと赤→緑に戻ることを確認)。解析画像(640×480)のままセンサー中央を切り出すので、
     * 顔の比率と画素の細かさが倍率どおり上がり、負荷は増えない。写る範囲は狭くなる。
     * 変えたら較正を消す(顔の大きさ・角度の基準が変わるため)。Full の docs/23 §3-6 から移植。
     */
    val frontCameraZoomRatio: Float = 1.0f,
    /** 運行開始時に位置情報の許可を促す画面を出さない(「次回から表示しない」にチェックした)。2026-10-17。 */
    val locationPromptSuppressed: Boolean = false,
    /**
     * 画面上部に数値(yaw・推論時間など)も出すか。**既定OFF**(2026-10-17、利用者の要望)。
     * OFFのときは「顔検出:OK 顔サイズ:OK(35%)…」の簡単な表示だけを大きめに出す。開発版でも同じ。
     */
    val showDiagnosticDetails: Boolean = false,
) {
    companion object {
        val DAY_MVP0_DEFAULT = DayMvpSettings()

        /** インカメラのズームの選択肢([frontCameraZoomRatio])。 */
        val FRONT_ZOOM_CHOICES = listOf(1.0f, 1.25f, 1.5f)
    }
