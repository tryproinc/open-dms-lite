    val eyeClosedCalibrationMaxSpread: Float = 0.12f,
    /**
     * 開と閉の差(正規化開眼比で 1.0 − 閉)の下限。**これを下回れば「目を閉じていない」か
     * 「サングラス等で瞼が読めない」。**どちらも閉眼判定が成立しない状態なので、較正で弾く。
     *
     * 2026-09-09の実車ログでは、サングラス着用時は目を閉じても正規化比が0.7〜0.8までしか
     * 下がらなかった(差0.2〜0.3)。素顔では0.43(差0.57)。
     */
    val eyeClosedCalibrationMinGap: Float = 0.30f,
    /**
     * 閾値を「閉」と「開」の間のどこに置くか。**0.30 = 閉から3割の位置。**
     *
     * 中点(0.5)ではない。眠気の閉眼は完全閉眼ではなく「うつろ」なので、
     * 閉側に寄せないと拾えない。PERCLOSの「80%閉じたら閉眼」と同じ考え方。
     * 2026-09-11の実測(閉0.43)では 0.43 + 0.30×0.57 = 0.60 になり、
     * 手で合わせてうまくいった値と一致する。
     */
    val eyeClosedCalibrationFraction: Float = 0.30f,
    /**
     * 算出した閾値をこの範囲に収める。較正の偏りで極端な値にならないようにする保険。
